// Regenera las migraciones de Prisma a partir de los scripts de base_de_datos/.
// Los scripts son la fuente (se usan en clase y con psql); las migraciones son la misma
// SQL sin las órdenes propias de psql, para crear la base en la nube con
// «npx prisma migrate deploy».   Uso: node prisma/generar-migraciones.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const aqui = dirname(fileURLToPath(import.meta.url));
const scripts = join(aqui, '..', '..', '..', 'base_de_datos');
const migraciones = join(aqui, 'migrations');

const limpiar = (archivo) =>
  readFileSync(join(scripts, archivo), 'utf8')
    .split(/\r?\n/)
    .filter((l) => !/^(BEGIN|COMMIT);\s*$/.test(l) && !l.startsWith('\\'))
    .join('\n');

const escribir = (carpeta, encabezado, partes) => {
  mkdirSync(join(migraciones, carpeta), { recursive: true });
  writeFileSync(join(migraciones, carpeta, 'migration.sql'), `-- ${encabezado}\n-- Generado por prisma/generar-migraciones.mjs: no editar a mano.\n\n${partes.map(limpiar).join('\n')}`);
};

mkdirSync(migraciones, { recursive: true });
writeFileSync(join(migraciones, 'migration_lock.toml'), '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
escribir('0_base', 'Base del sistema: 01_esquema, 02_comentarios y 05_ampliacion.', ['01_esquema.sql', '02_comentarios.sql', '05_ampliacion.sql']);
escribir('1_produccion', 'Preparación para producción: 06_produccion.', ['06_produccion.sql']);
escribir('2_comensal', 'Experiencia del comensal en la carta QR: 07_comensal.', ['07_comensal.sql']);
escribir('3_seguridad', 'Equipos vinculados y verificación en dos pasos: 08_seguridad.', ['08_seguridad.sql']);
console.log('Migraciones generadas en', migraciones);
